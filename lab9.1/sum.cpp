using namespace nsDod;
using namespace nsVar;

// Обчислює суму ряду s для аргументу x з точністю e.
// Додає доданки, поки модуль доданку більший за e.
void nsSum::sum()
{
    n = 0;
    a = x - 1;                            // перший доданок (n = 0): (x-1)^1 / 1
    s = a;
    do
    {
        n++;
        dod();                            // обчислення наступного доданку
        s += a;
    } while (fabs(a) > e);
}
