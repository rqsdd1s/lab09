// Обчислює доданок a з номером n через попередній доданок
// (рекурентне співвідношення):
//   a(n) = (-1)^n * (x-1)^(n+1) / (n+1)
//   a(n) / a(n-1) = -(x-1) * n / (n+1)   – коефіцієнт рекурентності
void nsDod::dod()
{
    a *= -(x - 1) * n / (n + 1.0);        // 1.0 – щоб ділення було дійсним
}
