#pragma once                              // захист від повторного включення

#include <iostream>

// Значення z. Від нього залежить, яка гілка формули буде компілюватися.
// Для директиви #if значення має бути цілою константою.
#define Z 12

// логічний вираз: умова першої гілки (z > 10)
#define FIRST_BRANCH (Z > 10)

#define SQR(a)    ((a) * (a))             // піднесення до квадрата
#define CUBE(a)   ((a) * (a) * (a))       // піднесення до куба
#define ABS(a)    ((a) < 0 ? -(a) : (a))  // модуль (абсолютне значення)
#define MAX(a, b) ((a) > (b) ? (a) : (b)) // більше з двох чисел
#define MIN(a, b) ((a) < (b) ? (a) : (b)) // менше з двох чисел

// виведення результату: #w перетворює вираз w на рядок
#define PRINT(w)  std::cout << #w " = " << (w) << std::endl
